import { Surreal } from 'surrealdb';
const db = new Surreal();
await db.connect('ws://127.0.0.1:8007/rpc');
await db.signin({ username: process.env.SURREAL_USER, password: process.env.SURREAL_PASS });
await db.use({ namespace: 'restaurant_manager', database: 'restaurant_manager' });
const run = async (label, q) => { try { console.log(label, JSON.stringify(await db.query(q)).slice(0, 260)); } catch (e) { console.log(label, 'ERR', e.message); } };
await run('cleanup', 'DELETE notes:live_smoke');
await run('create', "CREATE notes:live_smoke SET text = 'live write', created_at = time::now(), extra = { a: 1, b: 'x' }");
await run('read', 'SELECT * FROM notes:live_smoke');
await run('update', "UPDATE notes:live_smoke SET text = 'edited'");
await run('read2', 'SELECT * FROM notes:live_smoke');
await run('delete', 'DELETE notes:live_smoke');
await run('gone', 'SELECT * FROM notes:live_smoke');
await db.close();
