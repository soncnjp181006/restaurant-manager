def fit_image(path, max_w, max_h):
    with PILImage.open(path) as im:
        w, h = im.size
    r = min(max_w / w, max_h / h, 1.0)
    return Image(path, width=w * r, height=h * r)


def table_block(rows, ratios, header=True, align_cols=None):
    """rows: list of list[str]; first row = header. Returns centered styled Table."""
    data = []
    for i, row in enumerate(rows):
        line = []
        for j, cell in enumerate(row):
            if header and i == 0:
                line.append(Paragraph('<b>%s</b>' % cell, S['th']))
            else:
                st = S['tdc'] if (align_cols and j in align_cols) else S['td']
                line.append(Paragraph(cell, st))
        data.append(line)
    widths = [r * AVAIL_W for r in ratios]
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=1 if header else 0)
    style = [
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 4.5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4.5),
    ]
    if header:
        style.append(('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR))
        for i in range(1, len(rows)):
            style.append(('BACKGROUND', (0, i), (-1, i), TABLE_ROW_ODD if i % 2 == 0 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    return t


def callout_row(stats):
    """stats: list of (big, label). One row of stat boxes."""
    n = len(stats)
    gap = 10
    bw = (AVAIL_W - gap * (n - 1)) / n
    cells = []
    for big, label in stats:
        inner = Table([[Paragraph('<b>%s</b>' % big, S['stat'])], [Paragraph(label, S['statlabel'])]], colWidths=[bw - 2])
        inner.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
            ('BOX', (0, 0), (-1, -1), 0.9, ACCENT),
            ('TOPPADDING', (0, 0), (-1, 0), 9), ('BOTTOMPADDING', (0, 1), (-1, 1), 9),
            ('TOPPADDING', (0, 1), (-1, 1), 1), ('BOTTOMPADDING', (0, 0), (-1, 0), 1),
        ]))
        cells.append(inner)
    row = Table([cells], colWidths=[bw] * n, hAlign='CENTER')
    row.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0), ('RIGHTPADDING', (0, 0), (-1, -1), 0),
        ('TOPPADDING', (0, 0), (-1, -1), 0), ('BOTTOMPADDING', (0, 0), (-1, -1), 0),
    ]))
    return row


