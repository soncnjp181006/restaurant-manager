def ddl_snippet(table, max_lines=18):
    sql = open(os.path.join(DDL_DIR, '001_tables.sql'), encoding='utf-8').read()
    start = sql.index('CREATE TABLE `%s`' % table)
    end = sql.index('ENGINE=InnoDB', start) + len('ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;')
    lines = sql[start:end].splitlines()
    keep = [l for l in lines if not l.strip().startswith('KEY `')]
    if len(keep) > max_lines:
        keep = keep[:max_lines - 1] + ['  /* … */'] + [keep[-1]]
    from xml.sax.saxutils import escape
    return escape('\n'.join(keep))


