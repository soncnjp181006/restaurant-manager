/**
 * Generate the relational MySQL layout for every business table.
 *
 *   DB_HOST=127.0.0.1 DB_PORT=3307 DB_USER=restaurant DB_PASS=... \
 *     node migrations/relational/generate.mjs
 *
 * Reads the logical schema from migrations/latest.surql and the current rows
 * from `records` (needed for SCHEMALESS tables, column sizes, nullability and
 * to prove that every reference resolves), then writes:
 *
 *   migrations/relational/001_tables.sql        tables, child tables, indexes
 *   migrations/relational/002_foreign_keys.sql  FK constraints (after load)
 *   migrations/relational/report.json           counts + skipped constraints
 *   docs/erd/relational.mmd                     ERD of the physical FKs
 *
 * Flags:
 *   --source-only   read records from a JSON export instead of MySQL
 *   --export <f>    JSON export path ({table: [{id,data}]})
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import {
  parseSchema,
  buildModel,
  renderTables,
  renderForeignKeys,
  childTableName,
  attrsTableName,
} from './lib.mjs';

// mysql2 is installed for dbproxy; reuse it instead of adding a root dependency.
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const mysql = createRequire(path.join(ROOT, 'dbproxy', 'package.json'))('mysql2/promise');
const OUT_DIR = path.join(ROOT, 'migrations', 'relational');
const SCHEMA_FILE = path.join(ROOT, 'migrations', 'latest.surql');
const ERD_FILE = path.join(ROOT, 'docs', 'erd', 'relational.mmd');

const argv = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = argv.indexOf(`--${name}`);
  return i !== -1 && argv[i + 1] ? argv[i + 1] : fallback;
};

const SRC = {
  host: process.env.DB_HOST ?? process.env.MYSQL_HOST ?? '127.0.0.1',
  port: Number(process.env.DB_PORT ?? 3307),
  database: process.env.DB_NAME ?? process.env.MYSQL_DB ?? 'restaurant_manager',
  user: process.env.DB_USER ?? process.env.MYSQL_USER ?? 'restaurant',
  password: process.env.DB_PASS ?? process.env.MYSQL_PASSWORD,
  timezone: '+00:00',
};

async function loadFromMysql() {
  if (!SRC.password) throw new Error('DB_PASS (or MYSQL_PASSWORD) is required to read records');
  const conn = await mysql.createConnection(SRC);
  try {
    const [rows] = await conn.query('SELECT table_name, id, data FROM records ORDER BY table_name, id');
    const byTable = new Map();
    for (const row of rows) {
      if (!byTable.has(row.table_name)) byTable.set(row.table_name, []);
      const data = typeof row.data === 'string' ? JSON.parse(row.data) : row.data;
      byTable.get(row.table_name).push({ id: row.id, data });
    }
    return byTable;
  } finally {
    await conn.end();
  }
}

function loadFromFile(file) {
  const raw = JSON.parse(fs.readFileSync(file, 'utf8'));
  const byTable = new Map();
  for (const [table, rows] of Object.entries(raw)) byTable.set(table, rows);
  return byTable;
}

function buildErd(model) {
  const lines = [
    '%% Generated by migrations/relational/generate.mjs — physical FOREIGN KEY graph.',
    '%% One edge per declared record reference that resolves in the current data.',
    'erDiagram',
  ];
  for (const table of model) {
    for (const fk of table.foreignKeys) {
      const child = fk.childTable ?? table.name;
      const label = (fk.childColumn ?? fk.column).replace(/"/g, '');
      lines.push(`  ${child} }o--|| ${fk.refTable} : "${label}"`);
    }
  }
  return lines.join('\n') + '\n';
}

async function main() {
  const schemaText = fs.readFileSync(SCHEMA_FILE, 'utf8');
  const schema = parseSchema(schemaText);
  const rowsByTable = argv.includes('--source-only')
    ? loadFromFile(path.resolve(ROOT, opt('export', 'scratch/records-export.json')))
    : await loadFromMysql();

  const { model, warnings } = buildModel(schema, rowsByTable);

  const fkCount = model.reduce((n, t) => n + t.foreignKeys.length, 0);
  const columnCount = model.reduce((n, t) => n + t.columns.length, 0);
  const childCount = model.reduce((n, t) => n + t.arrays.length + (t.extras ? 1 : 0), 0);
  const withData = model.filter((t) => t.rowCount > 0).length;

  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUT_DIR, '001_tables.sql'), renderTables(model));
  fs.writeFileSync(path.join(OUT_DIR, '002_foreign_keys.sql'), renderForeignKeys(model));
  fs.writeFileSync(
    path.join(OUT_DIR, 'report.json'),
    JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        sourceDatabase: SRC.database,
        tables: model.length,
        tablesWithData: withData,
        rows: model.reduce((n, t) => n + t.rowCount, 0),
        columns: columnCount,
        childTables: childCount,
        foreignKeys: fkCount,
        warnings,
        perTable: model.map((t) => ({
          table: t.name,
          rows: t.rowCount,
          columns: t.columns.length,
          arrayFields: t.arrays.map((a) => ({
            field: a.field,
            childTable: childTableName(t.name, a.field),
            item: a.item,
            refTable: a.refTable,
          })),
          extras: t.extras ? attrsTableName(t.name) : null,
          foreignKeys: t.foreignKeys,
        })),
      },
      null,
      2
    )
  );
  fs.writeFileSync(ERD_FILE, buildErd(model));

  console.log(
    `tables ${model.length} (${withData} with data) · columns ${columnCount} · child tables ${childCount} · FKs ${fkCount} · rows ${model.reduce((n, t) => n + t.rowCount, 0)}`
  );
  if (warnings.length) {
    console.log(`\n${warnings.length} skipped constraint(s):`);
    for (const warning of warnings) console.log(`  - ${warning}`);
  }
  console.log(`\nwrote migrations/relational/001_tables.sql, 002_foreign_keys.sql, report.json, docs/erd/relational.mmd`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
